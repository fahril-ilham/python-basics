# Operand & Operator
## Operand: nilai asal yang akan diproses
## Operator: simbol untuk mendapatkan hasil olahan
hasil = 6/3 # 6 dan 3 adalah operand sedangkan simbol / adalah operator pembagian
print("Hasil 6 dibagi 3:", hasil)

# Jenis-Jenis Operator
## Operator Unary: hanya memiliki 1 operand
unary = +10
print(unary)
unary2 = -4
print(unary2)

## Operator Binary: menggunakan 2 operand
binary = 4*4
print(binary)

## Operator Ternary: menggunakan 3 operand

## Operator Aritmatika / Operator Matematika
penambahan = 3+7 # operator penambahan (+)
print("3 ditambah 7:", penambahan)
pengurangan = 9-4 # operator pengurangan (-)
print("9 dikurang 4:", pengurangan)
perkalian = 5*6 # operator perkalian (*)
print("5 dikali 6:", perkalian)
pembagian = 12/4 # operator pembagian (/)
print("12 dibagi 4:", pembagian)
floor_division = 11//5 # operator floor division (//), menghasilkan hasil bagi angka bulat
print("11 // 5:", floor_division)
pangkat = 2**8 # operator pangkat (**)
print("2 pangkat 8:", pangkat)
modulus = 20%7 # operator modulus (%), menghasilkan sisa pembagian
print("20 % 7:", modulus)

## Operator Perbandingan: membandingkan nilai 2 operand, menghasilkan tipe data boolean (True atau False)
operator1 = 5 == 6 # operator sama dengan
print("5 == 6:", operator1)
operator2 = "baju" != "kemeja" # operator tidak sama dengan
print("baju != kemeja:", operator2)
operator3 = 10 < 8 # operator kurang dari
print("10 < 8:", operator3)
operator4 = 8 > 3 # operator lebih dari
print("8 > 3:", operator4)
operator5 = 12 >= 10 # operator lebih dari atau sama dengan
print("12 >= 10:", operator5)
operator6 = 4 <= 3 # operator kurang dari atau sama dengan
print("4 <= 3:", operator6)

